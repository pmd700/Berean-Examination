import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createRequire } from 'node:module';
import { SyncReplica } from '../../shared/sync/replica.js';
import { importSyncKey, randomSecret } from '../../shared/sync/crypto.js';
import { importFile, pushFileOperation } from '../../shared/sync/files.js';
const require = createRequire(import.meta.url);
const { applyMigrations } = require('../../desktop/database.cjs');
const { PrivacyVault } = require('../../desktop/privacy-vault.cjs');
const { LocalEntityStore } = require('../../desktop/local-entity-store.cjs');
const { installEntityJournal, bootstrapEntityJournal } = require('../../desktop/sync/entity-journal.cjs');
const { VaultFileIndex } = require('../../desktop/sync/file-index.cjs');
const { FileBlobStore } = require('../../desktop/sync/blob-store.cjs');
const { SqliteReplicaStore } = require('../../desktop/sync/replica-store.cjs');
const { EntitySyncAdapter } = require('../../desktop/sync/entity-adapter.cjs');
const { applyFiles } = require('../../desktop/sync/file-apply.cjs');
const { readEncryptedAttachment } = require('../../desktop/local-attachments.cjs');
test('whole-file snapshots deduplicate backups, preserve phone attachment URLs, and retain tombstones', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(),'bex-sync-files-'));
  const libraryPath = path.join(root,'Vault'); fs.mkdirSync(libraryPath); fs.mkdirSync(path.join(libraryPath,'Media')); fs.mkdirSync(path.join(libraryPath,'Backups'));
  fs.writeFileSync(path.join(libraryPath,'Backups','a.bin'),Buffer.from('identical backup bytes')); fs.copyFileSync(path.join(libraryPath,'Backups','a.bin'),path.join(libraryPath,'Backups','b.bin'));
  const database = new DatabaseSync(':memory:'); applyMigrations(database);
  const { vault: privacyVault } = PrivacyVault.attach({ database,databasePath:':memory:',protector:{ protect:b=>Buffer.from(b),unprotect:b=>Buffer.from(b) } });
  const identity = { vaultId:crypto.randomUUID(),epoch:crypto.randomUUID(),deviceId:crypto.randomUUID(),slot:1 }, key = await importSyncKey(randomSecret());
  installEntityJournal(database,identity); bootstrapEntityJournal(database,identity);
  const blobs = new FileBlobStore(path.join(root,'cache')), index = new VaultFileIndex(database,privacyVault,libraryPath,blobs);
  const replica = new SyncReplica(new SqliteReplicaStore(':memory:',identity),key), phone = new SyncReplica(new SqliteReplicaStore(':memory:',{...identity,deviceId:crypto.randomUUID(),slot:2}),key);
  const adapter = new EntitySyncAdapter(database,privacyVault,new LocalEntityStore(database,privacyVault),identity,replica);
  const remote = new Map(), relay = { async request(route,options={}) { const hash=route.split('/').at(-1); if(options.method==='PUT') {remote.set(hash,options.body);return {ok:true};} if(!remote.has(hash))throw new Error('missing chunk');return remote.get(hash); } };
  try {
    await index.scan(key,identity); await adapter.drain();
    assert.equal(database.prepare('SELECT count(*) AS n FROM local_sync_file_content').get().n,1);
    const manifests=(await replica.records()).records.map(r=>r.versions[0].payload); assert.deepEqual(manifests[0].chunks,manifests[1].chunks);
    const count=database.prepare('SELECT count(*) AS n FROM local_sync_journal').get().n; await index.scan(key,identity); assert.equal(database.prepare('SELECT count(*) AS n FROM local_sync_journal').get().n,count);
    fs.unlinkSync(path.join(libraryPath,'Backups','a.bin')); await index.scan(key,identity); await adapter.drain(); assert.equal((await replica.record({kind:'VaultFile',id:'Backups/a.bin'})).status,'deleted');
    const phoneBlobs = new FileBlobStore(path.join(root,'phone-cache'));
    const file = new File(['%PDF-1.7\nExact phone PDF bytes'],'phone.pdf',{type:'application/pdf'});
    const manifest = await importFile(file,{ identity:(await phone.store.meta()).identity,replica:phone,blobs:phoneBlobs,changed(){} });
    for(const row of await phone.store.pending())await pushFileOperation(row,phone,phoneBlobs,relay);
    const rows=await phone.store.pending();await replica.receive(rows,{baseCursor:0,cursor:rows.length});
    await applyFiles({database,privacyVault,libraryPath,replica,relay,blobs});
    const attachment=readEncryptedAttachment({libraryPath,privacyVault,mediaUrl:manifest.url}); const chunks=[];for await(const bytes of attachment.body)chunks.push(Buffer.from(bytes));
    assert.equal(Buffer.concat(chunks).toString(),await file.text());
    assert.equal(fs.readFileSync(path.join(libraryPath,manifest.path)).includes(Buffer.from('Exact phone PDF bytes')),false);
    const before=database.prepare('SELECT count(*) AS n FROM local_sync_journal').get().n;await index.scan(key,identity);assert.equal(database.prepare('SELECT count(*) AS n FROM local_sync_journal').get().n,before);
  }finally{replica.store.close();phone.store.close();privacyVault.close();database.close();fs.rmSync(root,{recursive:true,force:true});}
});
